public enum TokenType {
    LEFT_BRACE,    // {
    RIGHT_BRACE,   // }
    LEFT_BRACKET,  // [
    RIGHT_BRACKET, // ]
    COLON,         // :
    COMMA,         // ,
    STRING,        // "..."
    NUMBER,        // 123, -1.5e10, etc.
    TRUE,          // true
    FALSE,         // false
    NULL,          // null
    EOF            // end of input
}
